    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        String nombre = txtNombre.getText().trim();
String telefono = txtTelefono.getText().trim();

if (nombre.isEmpty() || telefono.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Ingrese el nombre y el teléfono.");
} else {
    if (controlador.guardarContacto(nombre, telefono)) {
        JOptionPane.showMessageDialog(this,
                "Contacto guardado correctamente.");

        txtNombre.setText("");
        txtTelefono.setText("");
    } else {
        JOptionPane.showMessageDialog(this,
                "No se pudo guardar. Verifique si el nombre ya existe "
                + "o si la agenda está llena.");
    }
}
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String nombre = txtBuscar.getText().trim();

if (nombre.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Ingrese el nombre que desea buscar.");
} else {
    Contacto contacto = controlador.buscarContacto(nombre);

    if (contacto != null) {
        JOptionPane.showMessageDialog(this,
                "Contacto encontrado."
                + "\nNombre: " + contacto.getNombre()
                + "\nTeléfono: " + contacto.getTelefono());
    } else {
        JOptionPane.showMessageDialog(this,
                "El contacto no fue encontrado.");
    }
}
    }//GEN-LAST:event_btnBuscarActionPerformed

